"""Generate a SYNTHETIC placeholder PANORAMA database.

The values are random. They are NOT real data. Use them only to develop and
test the website until the real database dump is available.

The script writes one SQL file that creates the schemas `production` and
`diffusion` with the tables (in the real database: views) and columns that the
API reads. Usage:
    python generate.py > 10-synthetic.sql
"""
from __future__ import annotations

import random
import sys

SEED = 20211130
rng = random.Random(SEED)

# (id, ISO3 code, label). id 1 is the "Rest of the World", as in the real data.
AREAS = [
    (1, "ROW", "Rest of the World"), (2, "AUT", "Austria"), (3, "BEL", "Belgium"),
    (4, "DEU", "Germany"), (5, "ESP", "Spain"), (6, "FRA", "France"), (7, "ITA", "Italy"),
    (8, "NLD", "Netherlands"), (9, "POL", "Poland"), (10, "SWE", "Sweden"),
    (11, "FIN", "Finland"), (12, "CZE", "Czechia"),
]
# id 9 is "Rest of the elements", as in the real data.
ELEMENTS = [(1, "Copper"), (2, "Tantalum"), (3, "Cobalt"), (4, "Lithium"), (5, "Nickel"),
            (6, "Aluminium"), (7, "Zinc"), (8, "Neodymium"), (9, "Rest of the elements")]
PERIODS = [(2011, "2011"), (2016, "2016")]
PRODUCTS = [
    (101, "Copper ores and concentrates"), (102, "Refined copper"), (103, "Copper wire"),
    (104, "Tantalum capacitors"), (105, "Lithium-ion batteries"), (106, "Mobile phones"),
    (107, "Laptop computers"), (108, "Electric motors"), (109, "Passenger cars"),
    (110, "Wind turbines"), (111, "Household appliances"), (112, "Construction materials"),
]
CONTRIBUTOR_TYPES = [(1, "Industry"), (2, "Final demand")]
# (id, type, ISIC section, label)
CONTRIBUTORS = [
    (1, 1, "B - Mining and quarrying", "Mining of metal ores"),
    (2, 1, "C - Manufacturing", "Manufacture of basic metals"),
    (3, 1, "C - Manufacturing", "Manufacture of electronic components"),
    (4, 1, "C - Manufacturing", "Manufacture of electrical equipment"),
    (5, 1, "C - Manufacturing", "Manufacture of motor vehicles"),
    (6, 1, "D - Electricity and gas", "Electric power generation"),
    (7, 1, "F - Construction", "Construction of buildings"),
    (8, 2, None, "Final consumption expenditure by households"),
    (9, 2, None, "Final consumption expenditure by government"),
    (10, 2, None, "Gross fixed capital formation"),
]
INDUSTRIES = [c for c in CONTRIBUTORS if c[1] == 1]
FINAL_DEMAND = [c for c in CONTRIBUTORS if c[1] == 2]
COUNTRIES = [a for a in AREAS if a[1] != "ROW"]
REAL_ELEMENTS = [e for e in ELEMENTS if e[0] != 9]
SANKEY_STAGES = ["Extraction", "Primary production", "Manufacturing", "Use", "Waste management"]


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(round(v, 3)) if isinstance(v, float) else str(v)
    return "'" + str(v).replace("'", "''") + "'"


def size(code: str) -> float:
    """A stable size factor per country, so totals look plausible across charts."""
    return {"DEU": 5, "FRA": 4, "ITA": 3.5, "ESP": 3, "POL": 2.5, "NLD": 2, "SWE": 1.5,
            "BEL": 1.5, "AUT": 1.2, "CZE": 1.2, "FIN": 1, "ROW": 30}.get(code, 1)


def tonnes(scale: float = 1.0) -> float:
    return rng.lognormvariate(6, 1.3) * scale


class Writer:
    def __init__(self, out):
        self.out = out

    def raw(self, text: str) -> None:
        self.out.write(text + "\n")

    def table(self, name: str, columns: dict[str, str], rows: list[tuple]) -> None:
        cols = ", ".join(f"{c} {t}" for c, t in columns.items())
        self.raw(f"CREATE TABLE {name} ({cols});")
        self.raw(f"COMMENT ON TABLE {name} IS 'SYNTHETIC placeholder data - not real';")
        for i in range(0, len(rows), 500):
            values = ",\n  ".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows[i:i + 500])
            self.raw(f"INSERT INTO {name} ({', '.join(columns)}) VALUES\n  {values};")
        self.raw("")


def main(out=sys.stdout) -> None:
    w = Writer(out)
    w.raw("-- SYNTHETIC PLACEHOLDER DATA. Generated by db/synthetic/generate.py.")
    w.raw("-- The values are random and are NOT real PANORAMA data.\n")
    w.raw("CREATE SCHEMA production;\nCREATE SCHEMA diffusion;")
    w.raw("COMMENT ON SCHEMA diffusion IS 'SYNTHETIC placeholder data - not real';\n")

    w.table("production.codelist_contributortype",
            {"id": "integer", "contributortype_label": "text"}, CONTRIBUTOR_TYPES)
    w.table("production.contributor",
            {"id_contributor": "integer", "id_contributortype": "integer",
             "contributor_isic": "text", "contributor_label": "text"}, CONTRIBUTORS)
    w.table("diffusion.filtered_element", {"id": "integer", "element_label": "text"}, ELEMENTS)
    w.table("diffusion.filtered_period", {"id_period": "integer", "period_label": "text"},
            PERIODS)
    w.table("diffusion.filtered_product", {"id": "integer", "product_label": "text"}, PRODUCTS)
    w.table("diffusion.filtered_geographicarea",
            {"id_geographicarea": "integer", "geographicarea_code": "text",
             "geographicarea_label": "text"}, AREAS)

    # Domestic use of each element by country.
    use_rows, sector_rows, make_rows = [], [], []
    for area_id, code, _ in COUNTRIES:
        for period, _ in PERIODS:
            for el_id, el_label in ELEMENTS:
                scale = size(code) * (8 if el_id == 9 else 1)
                use_rows.append((area_id, period, el_id, el_label, tonnes(scale)))
                for _, ctype, isic, label in rng.sample(CONTRIBUTORS, 6):
                    sector_rows.append((el_id, area_id, period, isic, label,
                                        tonnes(scale / 4)))
    for _, code, _ in COUNTRIES:
        for period, _ in PERIODS:
            for el_id, _ in REAL_ELEMENTS:
                if rng.random() < 0.6:
                    make_rows.append((el_id, period, code, tonnes(size(code) * 2)))

    w.table("diffusion.element_use_by_country",
            {"id_geographicarea": "integer", "id_period": "integer", "id_element": "integer",
             "element_label": "text", "use_value": "numeric"}, use_rows)
    w.table("diffusion.element_use_by_country_by_economic_sector",
            {"id_element": "integer", "id_geographicarea": "integer", "id_period": "integer",
             "contributor_isic": "text", "contributor_label": "text", "use_value": "numeric"},
            sector_rows)
    w.table("diffusion.element_make_by_country",
            {"id_element": "integer", "id_period": "integer", "geographicarea_code": "text",
             "make_value": "numeric"}, make_rows)

    # Trade flows between all areas (including the Rest of the World).
    codes = [a[1] for a in AREAS]
    element_flows = [(el_id, period, s, t, tonnes(size(s) * size(t) / 10))
                     for el_id, _ in ELEMENTS for period, _ in PERIODS
                     for s in codes for t in codes if s != t and rng.random() < 0.7]
    w.table("diffusion.element_area_flow",
            {"id_element": "integer", "id_period": "integer", "source_region": "text",
             "target_region": "text", "global_use": "numeric"}, element_flows)

    flows = {"": [], "_intermediate_demand": [], "_final_demand": []}
    for prod_id, _ in PRODUCTS:
        for period, _ in PERIODS:
            for s in codes:
                for t in codes:
                    if s == t or rng.random() < 0.35:
                        continue
                    inter = tonnes(size(s) * size(t) / 20)
                    final = tonnes(size(s) * size(t) / 40)
                    flows[""].append((prod_id, period, s, t, inter + final))
                    flows["_intermediate_demand"].append((prod_id, period, s, t, inter))
                    flows["_final_demand"].append((prod_id, period, s, t, final))
    value_column = {"": "global_use", "_intermediate_demand": "intermediate_use",
                    "_final_demand": "final_use"}
    for suffix, rows in flows.items():
        w.table(f"diffusion.product_area_flow{suffix}",
                {"id_product": "integer", "id_period": "integer", "source_region": "text",
                 "target_region": "text", value_column[suffix]: "numeric"}, rows)
        # Country totals are the sums of the flows, so maps and flow lists agree.
        for direction, idx in (("import", 3), ("export", 2)):
            totals: dict[tuple, float] = {}
            for r in rows:
                key = (r[0], r[1], r[idx])
                totals[key] = totals.get(key, 0) + r[4]
            w.table(f"diffusion.product_{direction}_by_country{suffix}",
                    {"id_product": "integer", "id_period": "integer",
                     "geographicarea_code": "text", f"{direction}_value": "numeric"},
                    [(*k, v) for k, v in sorted(totals.items())])

    # Final demand of products, by final demand category and industry.
    fd_rows = []
    for area_id, code, _ in AREAS:
        for prod_id, _ in PRODUCTS:
            for period, _ in PERIODS:
                for _, ctype, isic, label in FINAL_DEMAND + rng.sample(INDUSTRIES, 3):
                    fd_rows.append((area_id, prod_id, period, isic, label,
                                    tonnes(size(code) / 3)))
    w.table("diffusion.product_use_by_country_by_final_demand",
            {"id_geographicarea": "integer", "id_product": "integer", "id_period": "integer",
             "contributor_isic": "text", "contributor_label": "text", "use_value": "numeric"},
            fd_rows)

    # Element composition of products (weight fractions that sum to 1).
    comp_rows = []
    for prod_id, _ in PRODUCTS:
        for area_id, _, _ in AREAS:
            for contrib in CONTRIBUTORS:
                for period, _ in PERIODS:
                    elements = rng.sample(ELEMENTS, rng.randint(2, 5))
                    weights = [[rng.random() for _ in elements] for _ in range(3)]
                    sums = [sum(ws) for ws in weights]
                    for i, (el_id, el_label) in enumerate(elements):
                        supply, inter, final = (weights[m][i] / sums[m] for m in range(3))
                        comp_rows.append((prod_id, area_id, contrib[0], period, el_id, el_label,
                                          supply, inter if contrib[1] == 1 else None,
                                          final if contrib[1] == 2 else None))
    w.table("diffusion.product_element_composition",
            {"id_product": "integer", "id_geographicarea": "integer",
             "id_contributor": "integer", "id_period": "integer", "id_element": "integer",
             "element_label": "text", "cmp_supply_value": "numeric",
             "cmp_intermuse_value": "numeric", "cmp_finaluse_value": "numeric"}, comp_rows)

    # Substance flow (Sankey) along the life cycle: each stage feeds the next.
    sankey_rows = []
    for el_id, _ in ELEMENTS:
        for area_id, code, _ in AREAS:
            for period, _ in PERIODS:
                order, inflow = 0, tonnes(size(code) * 3)
                for a, b in zip(SANKEY_STAGES, SANKEY_STAGES[1:]):
                    loss = inflow * rng.uniform(0.05, 0.25)
                    order += 1
                    sankey_rows.append((el_id, area_id, period, order, a, b, inflow - loss))
                    order += 1
                    sankey_rows.append((el_id, area_id, period, order, a,
                                        f"Losses from {a.lower()}", loss))
                    inflow -= loss
    w.table("diffusion.sankey_final_period_geographicarea_element",
            {"id_element": "integer", "id_geographicarea": "integer", "id_period": "integer",
             "ordre": "integer", "from_d": "text", "to_f": "text", "value": "numeric"},
            sankey_rows)


if __name__ == "__main__":
    main()
